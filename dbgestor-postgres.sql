-- Base de datos dbgestor para PostgreSQL
-- Convertido desde dump-dbgestor-202406261453.sql (MariaDB 11.3).
--
-- Uso (desde psql, conectado como postgres):
--   CREATE DATABASE dbgestor;
--   \c dbgestor
--   \i dbgestor-postgres.sql
--
-- Las columnas de fecha son varchar porque las entidades JPA las mapean como String
-- (MariaDB convertia texto a date de forma implicita; PostgreSQL no).

DROP TABLE IF EXISTS asignaciones;
DROP TABLE IF EXISTS comentarios;
DROP TABLE IF EXISTS tareas;
DROP TABLE IF EXISTS proyectos;
DROP TABLE IF EXISTS usuario;

CREATE TABLE usuario (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100),
  correo_electronico varchar(100),
  contrasena varchar(100),
  rol varchar(100),
  imagen_usuario varchar(255)
);

CREATE TABLE proyectos (
  id_proyecto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100),
  descripcion varchar(100),
  fecha_inicio varchar(30),
  fecha_finalizacion varchar(30),
  estado_proyecto varchar(100),
  fondo varchar(100)
);

CREATE TABLE tareas (
  id_tarea integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100),
  descripcion varchar(100),
  fecha_vencimiento varchar(30),
  estado varchar(255),
  lista varchar(255),
  id_proyecto integer
);

CREATE TABLE comentarios (
  id_comentario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  texto_comentario varchar(250),
  fecha_hora varchar(30),
  id_usuario varchar(100),
  id_tarea integer
);

CREATE TABLE asignaciones (
  id_asignacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer,
  id_tarea integer,
  fecha_asignacion varchar(30)
);
CREATE INDEX asignaciones_usuario_fk ON asignaciones (id_usuario);
CREATE INDEX asignaciones_tareas_fk ON asignaciones (id_tarea);

